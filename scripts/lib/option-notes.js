const key = s => String(s).trim().toLowerCase();

/** Trả về { [option text]: note } cho các phương án sai có ghi chú. */
function optionNotesFor(q) {
    let note = null;
    if (q.skill === 'vocabulary') {
        note = opt => (VOCABULARY[key(opt)] ? `'${opt}' = ${VOCABULARY[key(opt)]}.` : null);
    } else if (q.skill === 'grammar' || (q.skill === 'completion_error' && q.type === 'completion')) {
        note = opt => GRAMMAR[key(opt)] || null;
    }
    if (!note) return null;
    const notes = {};
    q.options.forEach((opt, i) => {
        if (i === q.answer) return;
        const text = note(opt);
        if (text) notes[opt] = text;
    });
    return Object.keys(notes).length ? notes : null;
}

module.exports = { optionNotesFor, GRAMMAR, VOCABULARY };
